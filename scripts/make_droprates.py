#!/usr/bin/env python3
"""Builds addon/Engine/Data/DropRates.lua from NeedRoll's dungeon and raid data (read only).

NeedRoll (by mikebvs, GPL v3) lists each boss's loot with its drop rate (CMaNGOS Classic-DB 1.12 rates, WoW Forever
rates from Wowhead where sampled: its files' own headers). This reads its Data/Dungeons/*.lua and Data/Raids/*.lua,
nothing else, and writes, for AzerothVeil's dungeon panel:
  FM.DROP_RATES.byBoss[<boss name, normalized>] = { [itemID] = rate (0..1) }
  FM.DROP_RATES.byItem[itemID] = rate     (an item with one rate wherever it drops: for the bosses NeedRoll groups
                                           under one encounter, Blackrock Depths' Ring of Law...)
Names are normalized as the addon looks them up: lower case, letters and digits only, a leading "the" dropped.

Usage: scripts/make_droprates.py [NeedRoll's folder]   (default: scripts/deploy.local.conf's AddOns folder/NeedRoll)
Run it again after a NeedRoll update. Nothing in NeedRoll's folder is written.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "addon", "Engine", "Data", "DropRates.lua")

ENCOUNTER = re.compile(r'\{\s*id\s*=\s*"([^"]+)"\s*,\s*name\s*=\s*"((?:[^"\\]|\\.)*)"\s*,\s*loot\s*=\s*\{')
ITEM = re.compile(r'\{\s*itemID\s*=\s*(\d+)\s*,\s*dropRate\s*=\s*([0-9.]+)\s*\}')
VERSION = re.compile(r'^##\s*Version:\s*(\S+)', re.M)


def default_dir():
    conf = os.path.join(ROOT, "scripts", "deploy.local.conf")
    if os.path.exists(conf):
        with open(conf, encoding="utf-8") as f:
            m = re.search(r'^WOW_ADDONS_DIR="([^"]+)"', f.read(), re.M)
        if m:
            return os.path.join(m.group(1), "NeedRoll")
    return None


def norm(name):
    name = name.lower()
    name = re.sub(r"^the\s+", "", name)
    return re.sub(r"[^0-9a-z]", "", name)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else default_dir()
    if not src or not os.path.isdir(os.path.join(src, "Data")):
        sys.exit("NeedRoll's folder not found (give it as the first argument)")
    version = "?"
    toc = os.path.join(src, "NeedRoll.toc")
    if os.path.exists(toc):
        with open(toc, encoding="utf-8", errors="replace") as f:
            m = VERSION.search(f.read())
            if m:
                version = m.group(1)
    by_boss, rates_of = {}, {}
    files = 0
    for sub in ("Dungeons", "Raids"):
        folder = os.path.join(src, "Data", sub)
        for fn in sorted(os.listdir(folder)):
            if not fn.endswith(".lua"):
                continue
            files += 1
            with open(os.path.join(folder, fn), encoding="utf-8", errors="replace") as f:
                text = f.read()
            heads = list(ENCOUNTER.finditer(text))
            for i, h in enumerate(heads):
                body = text[h.end():heads[i + 1].start() if i + 1 < len(heads) else len(text)]
                key = norm(h.group(2).encode().decode("unicode_escape"))
                for item, rate in ITEM.findall(body):
                    item, rate = int(item), float(rate)
                    if not (0 < rate <= 1):
                        continue
                    by_boss.setdefault(key, {})[item] = rate
                    rates_of.setdefault(item, set()).add(round(rate, 4))
    by_item = {i: next(iter(r)) for i, r in rates_of.items() if len(r) == 1}

    def num(r):
        return ("%.4f" % r).rstrip("0").rstrip(".")

    lines = [
        "-- AzerothVeil — Engine/Data/DropRates.lua: each boss's loot's drop rates, for the dungeon panel (UI/DungeonPanel.lua).",
        "-- Generated by scripts/make_droprates.py from NeedRoll %s (by mikebvs, GNU GPL v3), its Data/Dungeons and" % version,
        "-- Data/Raids: CMaNGOS Classic-DB 1.12 drop rates, WoW Forever rates from Wowhead where sampled (its own sources).",
        "-- Do not edit by hand: run the script again after a NeedRoll update. See NOTICE.md.",
        "local _, FM = ...",
        "",
        "FM.DROP_RATES = { byBoss = {",
    ]
    for key in sorted(by_boss):
        items = by_boss[key]
        body = ", ".join("[%d] = %s" % (i, num(items[i])) for i in sorted(items))
        lines.append('\t["%s"] = { %s },' % (key, body))
    lines.append("}, byItem = {")
    row = []
    for i in sorted(by_item):
        row.append("[%d] = %s" % (i, num(by_item[i])))
        if len(row) == 8:
            lines.append("\t" + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("\t" + ", ".join(row) + ",")
    lines.append("} }")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %d files, %d bosses, %d items with one rate (NeedRoll %s)" % (os.path.relpath(OUT, ROOT), files, len(by_boss), len(by_item), version))


if __name__ == "__main__":
    main()
